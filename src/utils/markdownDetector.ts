/**
 * 检测一段文本是否“明显含有 Markdown 语法”。
 *
 * 用于所见即所得编辑器的纯文本粘贴决策：只有确认文本确实携带 Markdown
 * 结构化语法（标题、列表、表格、代码围栏、成对的加粗/斜体等）时，才按
 * Markdown 解析渲染；否则一律当普通纯文本插入，避免把终端/配置文件里
 * 的 `[Unit]`、`a*b*c` 等误当成语法排版。
 *
 * 判断策略刻意偏保守：
 * - 只认“结构性”或“成对”的信号（如 `## ` 行首标题、`| a | b |` 表格、
 *   `**成对的星号**`、`` `成对的反引号` ``），不认孤立的单个符号。
 * - 单独的 `*`、`-`、`#`、孤立方括号 `[Unit]`、普通路径 `C:\x` 均不触发。
 */

// 行首块级语法：标题、引用、围栏代码、列表、表格分隔、分割线、扩展块。
const BLOCK_PATTERNS: RegExp[] = [
  // 标题：行首 1~6 个 # 后跟空白
  /(?:^|\n)\s{0,3}#{1,6}\s/u,
  // 围栏代码块 ``` 或 ~~~
  /(?:^|\n)\s{0,3}(`{3,}|~{3,})/u,
  // 引用块 >（含 callout > [!NOTE]）
  /(?:^|\n)\s{0,3}>[ \t]/u,
  // 有序列表 1.、10.
  /(?:^|\n)\s{0,3}\d+\.\s/u,
  // 任务列表 - [x] / - [ ]
  /(?:^|\n)\s{0,3}[-*+]\s\[[ xX]\]/u,
  // 无序列表项（连续两行以上，降低单个 "- " 误判）
  /(?:^|\n)(?:\s{0,3}[-+*]\s.+(?:\n|$)){2,}/u,
  // 表格：至少两行，且某行为纯表格分隔线 | - | - |
  /(?:^|\n)\s*\|[^|\n]*\|[^\n]*\n\s*\|[^\n]*:?-{3,}[^\n]*\|/u,
  // 分割线：独占一行，全由 -、*、_ 组成且至少三个（m 使 $ 匹配到行尾）
  /^\s{0,3}(?:-{3,}|\*{3,}|_{3,})\s*$/mu,
  // 块级公式 $$...$$
  /\$\$[\s\S]*?\$\$/u,
  // 扩展块 :::label
  /(?:^|\n)\s{0,3}:::[ \w-]*(?:\n|$)/u,
];

// 行内成对语法：加粗、斜体、删除线、高亮、行内代码、链接、图片、公式、脚注。
const INLINE_PATTERNS: RegExp[] = [
  // 加粗 **文字**
  /\*\*[^*\n]+\*\*/u,
  // 下划线加粗 __文字__
  /__[^_\n]+__/u,
  // 斜体 *文字*（要求星号前是行首或空白，避免把 a*b*c 误判）
  /(?:^|\s)\*[^*\n]+\*/u,
  // 删除线 ~~文字~~
  /~~[^~\n]+~~/u,
  // 高亮 ==文字==
  /==[^=\n]+==/u,
  // 行内代码 `code`
  /`[^`\n]+`/u,
  // 链接 [文字](地址)
  /\[[^\]\n]+\]\([^)\n]+\)/u,
  // 图片 ![文字](地址)
  /!\[[^\]\n]+\]\([^)\n]+\)/u,
  // 行内公式 $...$
  /\$[^$\n]+\$/u,
  // 脚注引用 [^标识]
  /\[\^[^\]\n]+\]/u,
];

/**
 * 判断文本是否明显含有 Markdown 语法。
 * @param text 待检测的纯文本
 * @returns 含结构化/成对 Markdown 语法返回 true，否则 false
 */
export const hasMarkdownSyntax = (text: string): boolean => {
  if (!text) return false;
  return (
    BLOCK_PATTERNS.some((pattern) => pattern.test(text))
    || INLINE_PATTERNS.some((pattern) => pattern.test(text))
  );
};